import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const origin = 'http://127.0.0.1:15201';
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ locale: 'ko-KR', viewport: { width: 1280, height: 800 } });
  await context.request.post(`${origin}/api/auth/local-preview`, { headers: { Origin: origin } });
  const me = await (await context.request.get(`${origin}/api/auth/me`)).json();
  await context.addInitScript(() => localStorage.setItem('pdfit.color-mode', 'dark'));
  const page = await context.newPage();
  await page.route('**/api/auth/me', (route) => route.fulfill({ json: { ...me, subscription: { ...me.subscription, status: 'trial', access: true, trialDaysRemaining: 10 } } }));
  let requests = 0;
  await page.route('**/api/tags/folder/*/auto', async (route) => {
    const books = route.request().postDataJSON().books;
    assert.ok(books.length > 0 && books.length <= 10);
    requests++;
    await route.fulfill({ json: { processed: books.length, failed: 0, addedTags: 0, books: books.map((book) => ({ ...book, addedTags: [], removedTags: [] })), errors: [] } });
  });
  await page.goto(`${origin}/folder/PDFit%20Library`);
  const button = page.getByTestId('ai-auto-tag-all');
  await button.waitFor();
  assert.equal(await button.innerText(), 'AI 자동태그 사용해 보기');
  assert.equal(await page.getByTestId('lnb-tags-section').getByTestId('HashTagIcon').count(), 1);
  const chip = page.getByTestId('pdf-tag-chip').first();
  if (await chip.count()) { assert.match(await chip.innerText(), /^#/); assert.equal(await chip.evaluate(el => getComputedStyle(el).borderTopWidth), '0px'); }
  for (let run = 1; run <= 2; run++) {
    const before = requests;
    await button.click();
    const dialog = page.getByRole('dialog');
    await dialog.getByTestId('ai-bulk-tag-trial-notice').waitFor();
    assert.match(await dialog.getByTestId('ai-bulk-tag-trial-notice').innerText(), /선택합니다.\n처리할 문서는/);
    if (run === 1) { for (let attempt = 0; attempt < 30 && await dialog.evaluate(el => getComputedStyle(el.closest('.MuiDialog-container')).opacity) !== '1'; attempt++) await new Promise(resolve => setTimeout(resolve, 50)); await mkdir('apps/pdfit/tests/reports/free-ai-repeat/20261006', { recursive: true }); await dialog.screenshot({ path: 'apps/pdfit/tests/reports/free-ai-repeat/20261006/free-ai-click.png' }); }
    await dialog.getByRole('button').last().click();
    for (let attempt = 0; attempt < 100 && (requests <= before || await button.isDisabled() || (await button.innerText()).includes('취소')); attempt++) await new Promise((resolve) => setTimeout(resolve, 50));
    assert.ok(requests > before);
    assert.equal(await button.isEnabled(), true);
  }
  assert.match(await page.getByTestId('ai-auto-tag-upgrade-guide').innerText(), /유료 이용권 결제 시/);
  const buttonBox = await button.boundingBox();
  const guideBox = await page.getByTestId('ai-auto-tag-upgrade-guide').boundingBox();
  assert.ok(guideBox.y >= buttonBox.y + buttonBox.height);
  assert.equal(await page.getByTestId('ai-auto-tag-upgrade-guide').evaluate(el => getComputedStyle(el).whiteSpace), 'nowrap');
  await page.mouse.move(0, 0);
  const noticeClose = page.locator('.MuiSnackbar-root button').last();
  if (await noticeClose.count()) await noticeClose.click();
  await new Promise(resolve => setTimeout(resolve, 250));
  await page.screenshot({ path: 'apps/pdfit/tests/reports/free-ai-repeat/20261006/free-ai-complete.png' });
  await page.locator('.pdfit-row-action-tags').first().click();
  const tagDialog = page.getByRole('dialog');
  await tagDialog.getByTestId('pdf-auto-classify-access-guide').waitFor();
  assert.equal(await tagDialog.getByTestId('pdf-auto-classify-access-guide').innerText(), '유료 이용권 결제 시 AI 자동 태그를 사용할 수 있습니다.');
  assert.equal(await tagDialog.getByRole('button', { name: 'PDF 자동 분류', exact: true }).isDisabled(), true);
  await context.addInitScript(() => localStorage.setItem('pdfit.color-mode', 'dark'));
  await page.reload();
  await page.locator('.pdfit-row-action-tags').first().click();
  await page.getByTestId('pdf-auto-classify-access-guide').waitFor();
  await page.mouse.move(0, 0);
  await mkdir('apps/pdfit/tests/reports/free-ai-repeat/20261006', { recursive: true });
  for (let attempt = 0; attempt < 30 && await page.getByRole('dialog').evaluate((element) => getComputedStyle(element.closest('.MuiDialog-container')).opacity) !== '1'; attempt++) await new Promise((resolve) => setTimeout(resolve, 50));
  await page.getByRole('dialog').screenshot({ path: 'apps/pdfit/tests/reports/free-ai-repeat/20261006/free-pdf-classify-guide.png' });
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '표지 보기', exact: true }).click();
  await page.getByTestId('pdf-cover-card').first().getByTestId('pdf-cover-file-actions').getByRole('button').first().click();
  const filenameLine = page.getByTestId('move-document-filename');
  await filenameLine.waitFor();
  assert.match(await filenameLine.innerText(), /^파일명 : .+\.pdf$/);
  assert.equal(await filenameLine.evaluate((element) => getComputedStyle(element).display), 'block');
  const destinationList = page.getByTestId('folder-destination-list');
  await destinationList.waitFor();
  const search = page.getByRole('textbox', { name: '폴더 검색', exact: true });
  await search.fill('없는폴더__검색');
  assert.equal(await destinationList.getByRole('radio').count(), 0);
  assert.equal(await destinationList.innerText(), '일치하는 폴더가 없습니다.');
  await search.fill('');
  assert.ok(await destinationList.evaluate(el => el.getBoundingClientRect().height) <= 202);
  assert.equal(await page.getByText('이동할 폴더를 선택하세요.', { exact: true }).count(), 0);
  const names = await destinationList.getByRole('radio').allInnerTexts();
  assert.deepEqual(names, [...names].sort((a,b) => a.localeCompare(b,'ko',{numeric:true,sensitivity:'base'})));
  for (const option of await destinationList.getByRole('radio').all()) assert.equal(await option.evaluate(el => el.getBoundingClientRect().height), 40);
  const choice = destinationList.getByRole('radio').first();
  await choice.click();
  assert.equal(await choice.getAttribute('aria-checked'), 'true');
  assert.equal(await page.getByRole('dialog').getByRole('button', { name: '이동', exact: true }).isEnabled(), true);
  await page.getByRole('dialog').screenshot({ path: 'apps/pdfit/tests/reports/free-ai-repeat/20261006/move-folder-list.png' });
  await page.getByRole('dialog').getByRole('button', { name: '취소', exact: true }).click();
  await page.getByTestId('pdf-cover-card').first().getByTestId('pdf-cover-file-actions').getByRole('button').last().click();
  const deleteDialog = page.getByRole('dialog');
  const cancel = deleteDialog.getByRole('button', { name: '취소', exact: true });
  const remove = deleteDialog.getByRole('button', { name: '삭제', exact: true });
  await page.mouse.move(0, 0);
  await new Promise(resolve => setTimeout(resolve, 250));
  const idle = await remove.evaluate(el => getComputedStyle(el).backgroundColor);
  assert.notEqual(await cancel.evaluate(el => getComputedStyle(el).color), 'rgb(59, 130, 246)');
  await remove.hover();
  await new Promise(resolve => setTimeout(resolve, 250));
  const hover = await remove.evaluate(el => getComputedStyle(el).backgroundColor);
  const brightness = color => color.match(/\d+/g).slice(0,3).map(Number).reduce((a,b)=>a+b,0);
  assert.ok(brightness(hover) > brightness(idle));
  await deleteDialog.screenshot({ path: 'apps/pdfit/tests/reports/free-ai-repeat/20261006/delete-confirm.png' });
  await cancel.click();
  console.log('무료 체험 계정: 자동태그 연속 2회 실행, 회당 최대 10개, 완료 후 버튼 활성 유지 통과');
} finally { await browser.close(); }
