import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
try {
 const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
 const origin = 'http://127.0.0.1:15201';
 await context.request.post(origin + '/api/auth/local-preview', { headers: { Origin: origin } });
 await context.addInitScript(() => { localStorage.setItem('pdfit.color-mode', 'light'); localStorage.setItem('pdfit.library.view', 'list'); });
 const page = await context.newPage();
 await page.goto(origin + '/folder/PDFit%20Library');
 await page.locator('.pdfit-row-action-tags').first().waitFor();
 const colors = await page.evaluate(() => ({ text: getComputedStyle(document.body).color, bg: getComputedStyle(document.body).backgroundColor }));
 assert.equal(colors.text, 'rgb(48, 52, 59)');
 assert.equal(colors.bg, 'rgb(248, 248, 248)');
 await mkdir('apps/pdfit/tests/reports/light-palette/20261006', { recursive: true });
 await page.screenshot({ path: 'apps/pdfit/tests/reports/light-palette/20261006/library.png' });
 await page.locator('.pdfit-row-action-tags').first().click();
 const dialog = page.getByRole('dialog');
 await dialog.getByRole('button', { name: '닫기', exact: true }).waitFor();
 assert.equal(await dialog.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
 await dialog.screenshot({ path: 'apps/pdfit/tests/reports/light-palette/20261006/tags.png' });
 await dialog.getByRole('button', { name: '닫기', exact: true }).click();
 await page.getByRole('button', { name: '표지 보기', exact: true }).click();
 await page.getByTestId('pdf-cover-card').first().waitFor();
 await page.screenshot({ path: 'apps/pdfit/tests/reports/light-palette/20261006/covers.png' });
 await page.goto(origin + '/pricing');
 const homeLink = page.getByTestId('lnb-home-link');
 await homeLink.waitFor();
 assert.equal(await homeLink.getAttribute('href'), '/');
 await homeLink.focus();
 await page.keyboard.press('Enter');
 await page.waitForURL(origin + '/');
 assert.equal(await page.getByTestId('lnb-preferences').count(), 1);
 await page.getByRole('link', { name: '라이브러리 열기', exact: true }).waitFor();
 await page.getByRole('heading').filter({ hasText: '수천 개의 PDF도' }).waitFor();
 assert.equal(await page.getByRole('heading', { name: 'PDFit의 핵심 가치' }).count(), 1);
 assert.equal(await page.getByRole('link', { name: '클립 보기', exact: true }).count(), 1);
 const library = page.getByRole('link', { name: '라이브러리 열기', exact: true });
 for (let attempt = 0; attempt < 40 && await library.getAttribute('aria-disabled') === 'true'; attempt++) await new Promise(resolve => setTimeout(resolve, 50));
 assert.notEqual(await library.getAttribute('aria-disabled'), 'true');
 await page.evaluate(() => document.activeElement?.blur());
 await page.mouse.move(1270, 790);
 await page.screenshot({ path: 'apps/pdfit/tests/reports/light-palette/20261006/home.png', fullPage: true });
 console.log('라이트 모드 본문 색상, 배경, 태그 모달 및 표지 보기 확인 통과');
} finally { await browser.close(); }
